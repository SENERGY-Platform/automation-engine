const deviceGroupPrefix = TypeDeviceRepository + "."

// the module type the device_repository task gives its groups
const deviceGroupModuleType = "device_repository_create_device_group"

// deviceGroupHandler creates or, by key, updates a device group at device-manager (TASK-25);
// behavior of smart-service-module-worker-device-repository.
type deviceGroupHandler struct {
	runtime *Runtime
}

func (this *deviceGroupHandler) Do(ctx context.Context, task Task) ([]model.Module, map[string]any, error) {
	deviceIds, used, err := this.deviceIds(task)
	if err != nil {
		return nil, nil, err
	}
	if !used {
		return nil, map[string]any{}, nil
	}
	name, ok := task.String(deviceGroupPrefix + "name")
	if !ok || name == "" {
		name = this.runtime.settings.DeviceGroupNamePrefix + task.InstanceId + "." + task.Id
	}
	wait := false
	if raw, ok := task.String(deviceGroupPrefix + "wait"); ok && raw != "" {
		if wait, err = strconv.ParseBool(raw); err != nil {
			this.runtime.logger.WarnContext(ctx, "unable to parse the wait value, defaulting to false", "value", raw)
			wait = false
		}
	}
	// unlike info, an empty key is a key
	key, hasKey := task.String(deviceGroupPrefix + "key")
	if hasKey {
		existing, err := this.runtime.existing(ctx, task, key, deviceGroupModuleType)
		if err != nil {
			return nil, nil, err
		}
		if len(existing) > 0 {
			if len(existing) > 1 {
				this.runtime.logger.WarnContext(ctx, "more than one module with the key", "key", key, "instance_id", task.RootInstanceId)
			}
			module := existing[0]
			groupId, exists := module.Data["device_group_id"]
			if exists {
				id, ok := groupId.(string)
				if !ok {
					return nil, nil, fmt.Errorf("module device-group-id output is not string: \n %#v", module)
				}
				setModuleUpdateVersion(&module)
				if err = this.send(ctx, task, http.MethodPut, id, deviceIds, name, wait); err != nil {
					return nil, nil, err
				}
				return []model.Module{module}, module.Data, nil
			}
			this.runtime.logger.WarnContext(ctx, "device-group-id output not found in module", "module_id", module.Id)
		}
		return this.create(ctx, task, deviceIds, name, wait, []string{key})
	}
	return this.create(ctx, task, deviceIds, name, wait, []string{})
}

func (this *deviceGroupHandler) create(ctx context.Context, task Task, deviceIds []string, name string, wait bool, keys []string) ([]model.Module, map[string]any, error) {
	var created models.DeviceGroup
	if err := this.sendRequest(ctx, task, http.MethodPost, "", deviceIds, name, wait, &created); err != nil {
		return nil, nil, err
	}
	option, _ := json.Marshal(compat.IotOption{DeviceGroupSelection: &compat.DeviceGroupSelection{Id: created.Id}})
	outputs := map[string]any{"done_event": "permission_done_" + created.Id, "device_group_id": created.Id, "device_group_iot_option": string(option)}
	module := model.Module{Id: task.ModuleId("create_device_group"), ModuleType: deviceGroupModuleType, Data: outputs, Keys: keys,
		DeleteInfo: &model.ModuleDeleteInfo{Url: this.runtime.settings.DeviceManagerUrl + "/device-groups/" + url.PathEscape(created.Id), UserId: task.Owner}}
	return []model.Module{module}, outputs, nil
}

func (this *deviceGroupHandler) send(ctx context.Context, task Task, method string, groupId string, deviceIds []string, name string, wait bool) error {
	return this.sendRequest(ctx, task, method, groupId, deviceIds, name, wait, nil)
}

// sendRequest writes the group with the attributes that mark it as generated by the instance
func (this *deviceGroupHandler) sendRequest(ctx context.Context, task Task, method string, groupId string, deviceIds []string, name string, wait bool, result any) error {
	if deviceIds == nil {
		deviceIds = []string{}
	}
	origin := this.runtime.settings.DeviceGroupAttributeOrigin
	group := models.DeviceGroup{Id: groupId, Name: name, DeviceIds: deviceIds, Attributes: []models.Attribute{
		{Key: "platform/generated", Value: "true", Origin: origin},
		{Key: "platform/smart_service_task", Value: task.Id, Origin: origin},
		{Key: "platform/smart_service_instance", Value: task.InstanceId, Origin: origin},
		{Key: "platform/smart_service_definition", Value: task.DeploymentId, Origin: origin},
	}}
	if len(deviceIds) > 0 {
		var helper struct {
			Criteria []models.DeviceGroupFilterCriteria `json:"criteria"`
		}
		err := this.runtime.request(ctx, this.runtime.http, http.MethodPost, this.runtime.settings.DeviceSelectionUrl+"/device-group-helper", task.Owner, false, deviceIds, &helper)
		if err != nil {
			return err
		}
		group.Criteria = helper.Criteria
	}
	target := this.runtime.settings.DeviceManagerUrl + "/device-groups"
	if method == http.MethodPut {
		target += "/" + url.PathEscape(groupId)
	}
	if wait {
		target += "?wait=true"
	}
	return this.runtime.request(ctx, this.runtime.http, method, target, task.Owner, false, group, result)
}

// deviceIds reads device_repository.create_device_group: a list, or its JSON, of device ids or
// device iot options; other entries are dropped
func (this *deviceGroupHandler) deviceIds(task Task) (result []string, used bool, err error) {
	name := deviceGroupPrefix + "create_device_group"
	value, ok := task.Inputs[name]
	if !ok {
		return nil, false, nil
	}
	var list []any
	switch v := value.(type) {
	case string:
		if err = json.Unmarshal([]byte(v), &list); err != nil {
			return nil, true, fmt.Errorf("unable to unmarshal value of %v to []interface{}: %w", name, err)
		}
	case []string:
		for _, s := range v {
			list = append(list, s)
		}
	case []any:
		list = v
	default:
		return nil, false, fmt.Errorf("unable to interpret value of %v (%#v)", name, value)
	}
	for _, element := range list {
		str, isString := element.(string)
		if !isString {
			raw, _ := json.Marshal(element)
			str = string(raw)
		}
		if id, ok := deviceIdOf(str); ok {
			result = append(result, id)
		}
	}
	return result, true, nil
}

func deviceIdOf(str string) (string, bool) {
	if strings.HasPrefix(str, models.URN_PREFIX+"device:") {
		return str, true
	}
	if strings.HasPrefix(str, models.URN_PREFIX) {
		return "", false
	}
	var option compat.IotOption
	if json.Unmarshal([]byte(str), &option) == nil && option.DeviceSelection != nil {
		return option.DeviceSelection.DeviceId, true
	}
	return "", false
}
